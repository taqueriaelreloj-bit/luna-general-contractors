"""Build the image sitemap for verified, published-page image assets.

This intentionally writes a separate image sitemap. The main sitemap is regenerated by
other site tooling and contains page URLs only, while this file pairs published images
with their canonical landing pages using Google's image sitemap extension.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath
from xml.sax.saxutils import escape


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "content" / "published-image-sitemap.json"
OUTPUT = ROOT / "image-sitemap.xml"
SITEMAP_NS = "http://www.sitemaps.org/schemas/sitemap/0.9"
IMAGE_NS = "http://www.google.com/schemas/sitemap-image/1.1"
ALLOWED_SUFFIXES = {".avif", ".gif", ".jpg", ".jpeg", ".png", ".webp"}


def fail(message: str) -> None:
    raise ValueError(message)


def load_manifest() -> tuple[str, list[dict[str, object]]]:
    try:
        data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"Cannot read image sitemap manifest: {error}") from error

    origin = data.get("siteOrigin")
    entries = data.get("entries")
    if not isinstance(origin, str) or not origin.startswith("https://") or origin.rstrip("/") != origin:
        fail("Manifest siteOrigin must be an HTTPS origin without a trailing slash.")
    if not isinstance(entries, list) or not entries:
        fail("Manifest needs one or more entries.")
    return origin, entries


def safe_asset_path(relative: str) -> Path:
    candidate = PurePosixPath(relative)
    if candidate.is_absolute() or ".." in candidate.parts or not candidate.parts:
        fail(f"Unsafe image path: {relative}")
    if candidate.suffix.lower() not in ALLOWED_SUFFIXES:
        fail(f"Unsupported image extension: {relative}")
    path = ROOT.joinpath(*candidate.parts)
    if not path.is_file():
        fail(f"Published image is missing: {relative}")
    return path


def normalize(origin: str, entries: list[dict[str, object]]) -> list[tuple[str, str, list[str]]]:
    output: list[tuple[str, str, list[str]]] = []
    seen_pages: set[str] = set()
    seen_images: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict):
            fail("Each image sitemap entry must be an object.")
        page = entry.get("page")
        canonical = entry.get("canonical")
        images = entry.get("images")
        if not isinstance(page, str) or not page.endswith(".html") or "/" in page or not (ROOT / page).is_file():
            fail(f"Invalid published page: {page!r}")
        if not isinstance(canonical, str) or not canonical.startswith(f"{origin}/"):
            fail(f"Invalid canonical URL: {canonical!r}")
        if page == "index.html" and canonical != f"{origin}/":
            fail("The homepage canonical must be the site root.")
        if page != "index.html" and canonical != f"{origin}/{page}":
            fail(f"Canonical does not match page: {page}")
        if canonical in seen_pages:
            fail(f"Duplicate canonical page: {canonical}")
        if not isinstance(images, list) or not images:
            fail(f"No images listed for {page}")

        html = (ROOT / page).read_text(encoding="utf-8")
        normalized_images: list[str] = []
        for image in images:
            if not isinstance(image, str):
                fail(f"Invalid image path in {page}")
            safe_asset_path(image)
            if image in seen_images:
                fail(f"An image sitemap asset may appear under only one canonical page: {image}")
            if f'src="{image}"' not in html and f"src='{image}'" not in html:
                fail(f"Image is not exposed through an HTML src on {page}: {image}")
            seen_images.add(image)
            normalized_images.append(image)
        seen_pages.add(canonical)
        output.append((page, canonical, normalized_images))
    return output


def render(origin: str, entries: list[tuple[str, str, list[str]]]) -> str:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<urlset xmlns="{SITEMAP_NS}" xmlns:image="{IMAGE_NS}">',
    ]
    for _page, canonical, images in entries:
        lines.append("  <url>")
        lines.append(f"    <loc>{escape(canonical)}</loc>")
        for image in images:
            lines.append("    <image:image>")
            lines.append(f"      <image:loc>{escape(f'{origin}/{image}')}</image:loc>")
            lines.append("    </image:image>")
        lines.append("  </url>")
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify that image-sitemap.xml is current without writing it.")
    args = parser.parse_args()

    origin, raw_entries = load_manifest()
    markup = render(origin, normalize(origin, raw_entries))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != markup:
            print("image-sitemap.xml is stale; run python scripts/build-image-sitemap.py", file=sys.stderr)
            return 1
        print("Verified image sitemap.")
        return 0

    OUTPUT.write_text(markup, encoding="utf-8", newline="\n")
    print(f"Built image sitemap with {sum(len(images) for _, _, images in normalize(origin, raw_entries))} image URLs.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ValueError as error:
        print(f"Image sitemap error: {error}", file=sys.stderr)
        raise SystemExit(1)
